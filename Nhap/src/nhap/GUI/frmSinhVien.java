    private void loadTable(){
        DefaultTableModel model = (DefaultTableModel) tblSinhVien.getModel();
        model.setRowCount(0);

        for(SinhVien1 sv : ql.getSv()){
            model.addRow(new Object[]{
                sv.getTen(),
                sv.getTuoi(),
                sv.getDtb()
            });
        }
    }
    private void loadTableDefault(){
        DefaultTableModel model = (DefaultTableModel) tblSinhVien.getModel();
        model.setRowCount(0);

        for(SinhVien1 sv : svs.getAll()){
            model.addRow(new Object[]{
                sv.getId(),
                sv.getTen(),
                sv.getTuoi(),
                sv.getDtb()
            });
        }
    }
